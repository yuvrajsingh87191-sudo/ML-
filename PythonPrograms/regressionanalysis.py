import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression

# Generate the data
x =  10*np.random.rand(50)
y =  2*x - 5 + np.random.randn(50)

# Fit a Linear regression model
x = x.reshape(-1,1)
model = LinearRegression()
model.fit(x,y)

# Calculate the predicted values
y_pred = model.predict(x)

# plot the scatter plot and regression lines
plt.scatter(x,y,label="Data Points")
plt.xlabel("X")
plt.ylabel("Y")
plt.title("Scatter plot with increased variability and regression lines")

# Plot the actual population line
x_line = np.linspace(0,10,100)
y_actual = 2*x_line - 5
plt.plot(x_line,y_actual,'r',label="Population Line (m=2,b=-5)")

# Plot the estimated regression line
y_estimated = model.coef_[0]*x_line + model.intercept_
plt.plot(x_line,y_estimated,'g',label=f"Estimated Regression Line(m={model.coef_[0]:.2f},b={model.intercept_:.2f})")


plt.legend()
plt.show()

