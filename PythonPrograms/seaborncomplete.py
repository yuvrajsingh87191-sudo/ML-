# hue
sns.violinplot(data=tips,x='day',y='total_bill',hue='sex')

sns.violinplot(data=tips,x='day',y='total_bill',hue='sex', split=True)

# barplot
sns.barplot(data=tips,x='sex',y='total_bill',hue='day')

"""When there are multiple observations in each category , it also uses bootstrapping to compute a confidence interval around the estimate , which is plotted using error bars."""

import numpy as np
sns.barplot(data=tips,x='sex',y='total_bill',hue='smoker',estimator= np.min)

# countplot
sns.countplot(data=tips,x='sex')

"""A special case for the bar plot is when you want to show the number of observation in each category rather than computing a statistic for a second variable . This is similar to a histogram over a categorical , rather than quantitative , variable"""

# point plot
import numpy as np
sns.pointplot(data=tips,x='sex',y='total_bill',hue='smoker',estimator= np.min)

# faceting using catplot
sns.catplot(data=tips,x='sex',y='total_bill',hue='smoker' , kind='box',row ='time')
#

"""## **REgression plot **

*   regplot
*   Lmplot

In the simplest invocation , both functions draw a scatterplot of two varibles , x and y , and then fit the regression model y~x and plot the resulting regression line and a 95% confidence for that regression
"""

# regplot
