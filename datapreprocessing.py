import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Load the dataset
try:
    df = pd.read_csv('cupcake.csv')
    print("Dataset loaded successfully. Here's a peek at the data:")
    print(df.head())
    print("\nAnd here are the columns:")
    print(df.columns.tolist())

    # --- Descriptive Statistics ---
    print("\n--- Descriptive Statistics ---")
    # Iterate through numeric columns for statistics
    for col in df.select_dtypes(include=np.number).columns:
        print(f"\nStatistics for column: {col}")
        mean_val = df[col].mean()
        median_val = df[col].median()
        mode_val = df[col].mode().tolist() # mode can return multiple values
        variance_val = df[col].var()
        std_dev_val = df[col].std() # Standard deviation as dispersion

        Q1 = df[col].quantile(0.25)
        Q3 = df[col].quantile(0.75)
        iqr = Q3 - Q1

        print(f"  Mean: {mean_val:.2f}")
        print(f"  Median: {median_val:.2f}")
        print(f"  Mode: {mode_val}")
        print(f"  Variance: {variance_val:.2f}")
        print(f"  Standard Deviation (Dispersion): {std_dev_val:.2f}")
        print(f"  Interquartile Range (IQR): {iqr:.2f}")

    # --- Visualizations ---
    print("\n--- Visualizations ---")
    # Assuming you want to plot the first two numeric columns if available
    numeric_cols = df.select_dtypes(include=np.number).columns.tolist()

    if len(numeric_cols) >= 2:
        # Scatter Plot
        plt.figure(figsize=(10, 6))
        sns.scatterplot(x=df[numeric_cols[0]], y=df[numeric_cols[1]])
        plt.title(f'Scatter Plot of {numeric_cols[0]} vs {numeric_cols[1]}')
        plt.xlabel(numeric_cols[0])
        plt.ylabel(numeric_cols[1])
        plt.grid(True)
        plt.show()
    elif len(numeric_cols) == 1:
        print("Not enough numeric columns for a scatter plot with two variables. Plotting a distribution plot instead.")
        plt.figure(figsize=(10, 6))
        sns.histplot(df[numeric_cols[0]], kde=True)
        plt.title(f'Distribution Plot of {numeric_cols[0]}')
        plt.xlabel(numeric_cols[0])
        plt.ylabel('Frequency')
        plt.grid(True)
        plt.show()
    else:
        print("No numeric columns found for scatter plot.")

    if len(numeric_cols) >= 1:
        # Box Plot
        plt.figure(figsize=(10, 6))
        sns.boxplot(data=df[numeric_cols])
        plt.title('Box Plot of Numeric Columns')
        plt.ylabel('Values')
        plt.grid(True)
        plt.show()
    else:
        print("No numeric columns found for box plot.")

except FileNotFoundError:
    print("Error: 'cupcake.csv' not found. Please make sure the file is in the correct directory.")
except Exception as e:
    print(f"An error occurred: {e}")

