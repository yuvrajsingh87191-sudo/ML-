import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("/content/hotel_bookings.csv")
print(df.head())
print(df.columns)

# --- Descriptive Statistics for hotel_bookings.csv ---
print("\n--- Descriptive Statistics for hotel_bookings.csv ---")

try:
    # Get all numeric columns
    numeric_cols_hotel = df.select_dtypes(include=np.number).columns.tolist()

    if not numeric_cols_hotel:
        print("No numeric columns found in the hotel dataset for statistical analysis.")
    else:
        for col in numeric_cols_hotel:
            print(f"\nStatistics for column: {col}")

            # Handle columns with all NaN values or non-numeric types gracefully
            if df[col].isnull().all() or not pd.api.types.is_numeric_dtype(df[col]):
                print(f"  Cannot compute statistics for '{col}' due to non-numeric or all NaN values.")
                continue

            mean_val = df[col].mean()
            median_val = df[col].median()
            mode_val = df[col].mode().tolist()
            variance_val = df[col].var()
            std_dev_val = df[col].std()

            Q1 = df[col].quantile(0.25)
            Q3 = df[col].quantile(0.75)
            iqr = Q3 - Q1

            print(f"  Mean: {mean_val:.2f}")
            print(f"  Median: {median_val:.2f}")
            print(f"  Mode: {mode_val}")
            print(f"  Variance: {variance_val:.2f}")
            print(f"  Standard Deviation (Dispersion): {std_dev_val:.2f}")
            print(f"  Interquartile Range (IQR): {iqr:.2f}")

    # --- Visualizations for hotel_bookings.csv ---
    print("\n--- Visualizations for hotel_bookings.csv ---")

    # Box Plot for all numeric columns
    if numeric_cols_hotel:
        plt.figure(figsize=(15, 8))
        sns.boxplot(data=df[numeric_cols_hotel])
        plt.title('Box Plot of Numeric Columns in Hotel Bookings Data')
        plt.ylabel('Values')
        plt.xticks(rotation=45, ha='right')
        plt.grid(axis='y')
        plt.tight_layout()
        plt.show()
    else:
        print("No numeric columns to create box plots.")

    # Scatter Plot - Example with 'lead_time' and 'adr'
    # Checking if these specific columns exist and are numeric
    if 'lead_time' in df.columns and 'adr' in df.columns and \
       pd.api.types.is_numeric_dtype(df['lead_time']) and pd.api.types.is_numeric_dtype(df['adr']):
        plt.figure(figsize=(10, 6))
        sns.scatterplot(x='lead_time', y='adr', data=df)
        plt.title('Scatter Plot of Lead Time vs. Average Daily Rate (ADR)')
        plt.xlabel('Lead Time (days)')
        plt.ylabel('Average Daily Rate (ADR)')
        plt.grid(True)
        plt.show()
    else:
        print("Cannot create scatter plot for 'lead_time' vs 'adr' as one or both columns are missing or not numeric.")

except Exception as e:
    print(f"An error occurred during hotel_bookings analysis: {e}")